/**
 * Markdown reporter, suitable for pull-request comments.
 */

export function renderMarkdown(report) {
  const s = report.summary;
  const verdict = s.failed > 0 ? '❌ FAIL' : s.review > 0 ? '⚠️ REVIEW' : '✅ PASS';
  const out = [];

  out.push(`## SkillSleuth report ${verdict}`);
  out.push('');
  out.push(
    `Scanned **${s.skills}** skill(s) with **${report.ruleCount}** rules — **${s.findings}** findings ` +
      `(${s.counts.critical} critical, ${s.counts.high} high, ${s.counts.medium} medium, ${s.counts.low} low).`
  );
  out.push('');

  if (report.skills.length === 0) {
    out.push('_No skills found. A skill is a folder containing `SKILL.md`._');
    return out.join('\n');
  }

  out.push('| Skill | Verdict | Score | Critical | High | Medium | Low |');
  out.push('|---|---|---:|---:|---:|---:|---:|');
  for (const skill of report.skills) {
    const icon = skill.verdict === 'fail' ? '❌' : skill.verdict === 'review' ? '⚠️' : '✅';
    out.push(
      `| \`${skill.path}\` | ${icon} ${skill.verdict} | ${skill.score} | ${skill.counts.critical} | ${skill.counts.high} | ${skill.counts.medium} | ${skill.counts.low} |`
    );
  }
  out.push('');

  for (const skill of report.skills) {
    if (skill.findings.length === 0) continue;
    out.push(`<details><summary><strong>${skill.path}</strong> — ${skill.findings.length} findings</summary>`);
    out.push('');
    for (const f of skill.findings) {
      out.push(
        `- **${f.severity.toUpperCase()}** \`${f.ruleId}\` **${f.title}** — \`${f.file}:${f.line}\`${f.allowed ? ' _(allowed)_' : ''}`
      );
      if (f.match) out.push(`  - \`${f.match}\``);
      if (f.remediation) out.push(`  - fix: ${f.remediation}`);
    }
    out.push('');
    out.push('</details>');
    out.push('');
  }

  out.push('---');
  out.push('_Generated by [SkillSleuth](https://github.com/AdilSiddiquiHQ/skillsleuth)._');
  return out.join('\n');
}
